-- ---------------------------------------------------------------------------
-- quests.xp_value に NOT NULL を付与する。
--
-- 生成元の CASE 式は effort の 3 値をすべて網羅しており、effort 自体も NOT NULL
-- であるため、この列が null になることはない。しかし PostgreSQL はそれを証明
-- できないため、内省結果は nullable となり、生成される型も `number | null` に
-- なる。実際には起こらない null の取り回しが全呼び出し側へ波及するため、
-- 制約として明示する。
-- ---------------------------------------------------------------------------

alter table public.quests
  alter column xp_value set not null;
